function config = exp2_defaults(presetIndex)
%EXP2_DEFAULTS Return equation presets and a ready-to-run configuration.

presetData(1) = struct( ...
    'name', '方程 f₁', ...
    'formula', 'f₁(x) = x⁴ − 5x³ − 12x² + 76x − 79', ...
    'coefficients', [1 -5 -12 76 -79], ...
    'initialX', 1.8, ...
    'bracket', [1.7 1.8], ...
    'plotBounds', [-5 6]);
presetData(2) = struct( ...
    'name', '方程 f₂', ...
    'formula', 'f₂(x) = x³ − 8x² + 17x − 10', ...
    'coefficients', [1 -8 17 -10], ...
    'initialX', 2.1, ...
    'bracket', [1.9 2.1], ...
    'plotBounds', [0 6]);

if nargin < 1
    presetIndex = 1;
end
if ~(isnumeric(presetIndex) && isscalar(presetIndex) && ...
        isfinite(presetIndex) && presetIndex == fix(presetIndex) && ...
        presetIndex >= 1 && presetIndex <= numel(presetData))
    error('exp2:InvalidPreset', '方程预设编号无效。');
end

preset = presetData(presetIndex);
config = struct();
config.presets = presetData;
config.presetIndex = presetIndex;
config.equationName = preset.name;
config.formula = preset.formula;
config.coefficients = preset.coefficients;
config.initialX = complex(preset.initialX, 0);
config.bracket = preset.bracket;
config.xTolerance = 1e-10;
config.residualTolerance = 1e-10;
config.maxIterations = 100;
config.plotBounds = preset.plotBounds;
end
